'use strict';

(()=>{const root=document.getElementById('portal-showcase');
if(!root)return;
const features={learning:['A clear path through your courses','Open enrolled courses and follow their modules, lessons and assessment tasks.',['Course modules and resources','Assignments and submission history','Progress and completion requirements']],classes:['Your classes, organised','Find cohort sessions, class times and attendance in the learner portal.',['Scheduled sessions','Instructor-led learning','Attendance records']],code:['Practise in your browser','Use the existing programming workspace alongside supported coding tasks.',['Language selection and code editor','Output and task context','Work-pattern reports where enabled']],feedback:['Know what to improve next','Read grades and instructor feedback on your submitted work.',['Reviewed assignments','Submission history','Feedback for your next attempt']],progress:['See how far you have come','Review learning activity, grades and achievements in one account.',['Course progress','Assessment results','Gems and certificates']],career:['Make your skills visible','Build a talent profile and explore opportunities using the existing career tools.',['Skills and project profile','Hiring-interest preferences','Jobs and challenges']]};
const tabs=[...root.querySelectorAll('[role=tab]')];
 const dialog=document.createElement('dialog');
dialog.className='portal-preview-dialog';
dialog.innerHTML='<button type=button class=portal-secondary>Close preview</button><div class=portal-preview-pan><img alt="Expanded student demo preview"></div>';
document.body.append(dialog);
dialog.querySelector('button').addEventListener('click',()=>dialog.close());
root.querySelectorAll('figure').forEach(figure=>{const button=document.createElement('button');
button.type='button';
button.className='portal-secondary portal-expand';
button.textContent='Expand preview';
button.addEventListener('click',()=>{const source=figure.querySelector('img');
const image=dialog.querySelector('img');
image.src=source.src;
image.alt=source.alt;
dialog.showModal()});
figure.append(button)});
const track=(event,params={})=>{if(typeof window.gtag==='function')window.gtag('event',event,params)};
function select(tab){for(const t of tabs){const active=t===tab;
t.setAttribute('aria-selected',active);
t.tabIndex=active?0:-1}const key=tab.dataset.portalFeature,[title,description,bullets]=features[key];
document.getElementById('portal-feature').setAttribute('aria-labelledby',tab.id);
document.getElementById('portal-feature-title').textContent=title;
document.getElementById('portal-feature-description').textContent=description;
document.getElementById('portal-feature-bullets').replaceChildren(...bullets.map(text=>{const li=document.createElement('li');
li.textContent=text;
return li}));
const img=document.getElementById('portal-feature-image');
img.src=img.src.replace(/[^/]+\.webp$/ ,key+'.webp');
img.alt='Actual EchoLens student demo: '+tab.textContent;
track('portal_feature_viewed',{feature:key});
}tabs.forEach((tab,i)=>{tab.addEventListener('click',()=>select(tab));
tab.addEventListener('keydown',e=>{let next;
if(e.key==='ArrowRight')next=(i+1)%tabs.length;
if(e.key==='ArrowLeft')next=(i+tabs.length-1)%tabs.length;
if(e.key==='Home')next=0;
if(e.key==='End')next=tabs.length-1;
if(next!==undefined){e.preventDefault();
tabs[next].focus();
select(tabs[next]);
tabs[next].scrollIntoView({block:'nearest',inline:'nearest'})}})});
document.addEventListener('click',e=>{const link=e.target.closest('a');
if(!link)return;
if(link.dataset.showcaseEvent)track(link.dataset.showcaseEvent);
else if(link.closest('#learning-options')){if(link.hash==='#free')track('free_course_cta_clicked');
if(link.hash==='#paid')track('paid_course_cta_clicked')}});
if('IntersectionObserver'in window){const observer=new IntersectionObserver(entries=>{if(entries.some(e=>e.isIntersecting)){track('certificate_section_viewed');
observer.disconnect()}},{threshold:.25});
observer.observe(document.getElementById('certificate-options'));
}})();
